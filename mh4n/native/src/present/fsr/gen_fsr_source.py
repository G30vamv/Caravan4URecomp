"""Makes fsr_source.inc from AMD's FidelityFX FSR 1 headers (ffx_a.h and ffx_fsr1.h, MIT license, LICENSE-FidelityFX-FSR.txt):
the comment-only lines are left out and the text is cut in raw string pieces, which the compositor joins and compiles as GLSL.

    python gen_fsr_source.py            (run it in this folder; the .inc is committed, so it is only needed when the headers change)
"""

import os

HERE = os.path.dirname(os.path.abspath(__file__))
CHUNK = 12000


def squeeze(text):
    out = []
    for raw in text.replace("\r\n", "\n").split("\n"):
        line = raw.rstrip()
        stripped = line.strip()
        if not stripped or stripped.startswith("//"):
            continue
        out.append(line)
    return "\n".join(out) + "\n"


def pieces(name, text):
    parts = []
    lines = text.split("\n")
    current = ""
    for line in lines:
        if len(current) + len(line) + 1 > CHUNK and current:
            parts.append(current)
            current = ""
        current += line + "\n"
    if current:
        parts.append(current)
    body = "\n".join(f'    R"FSR({p})FSR"' for p in parts)
    return f"inline const char* const {name} =\n{body};\n"


def main():
    a = squeeze(open(os.path.join(HERE, "ffx_a.h"), encoding="utf-8", errors="replace").read())
    f = squeeze(open(os.path.join(HERE, "ffx_fsr1.h"), encoding="utf-8", errors="replace").read())
    with open(os.path.join(HERE, "fsr_source.inc"), "w", encoding="utf-8", newline="\n") as out:
        out.write("// Generated by gen_fsr_source.py from AMD FidelityFX FSR 1 (ffx_a.h, ffx_fsr1.h): Copyright (c) 2021 Advanced Micro Devices, Inc.\n")
        out.write("// MIT license (LICENSE-FidelityFX-FSR.txt). Comment lines left out; do not edit by hand.\n")
        out.write(pieces("kFfxA", a))
        out.write(pieces("kFfxFsr1", f))
    print("fsr_source.inc:", os.path.getsize(os.path.join(HERE, "fsr_source.inc")), "bytes")


if __name__ == "__main__":
    main()
