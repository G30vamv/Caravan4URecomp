ReadbackData& ReadbackState(Backend::Impl& backend) {
    static std::mutex init_mutex;
    std::lock_guard lock(init_mutex);
    if (!backend.readback) {
        backend.readback = {new ReadbackData, [](ReadbackData* data) { delete data; }};
    }
    return *backend.readback;
}

Result<void> readback::CheckSubmitted(Backend::Impl& backend, Image::Impl& image, const char* who) {
    const auto* open = targets::OpenRecorder(backend, std::this_thread::get_id());
    if (open && open->targets) {
        const auto& touched = open->targets->touched;
        if (image.open_pass_in == open || std::ranges::any_of(touched, [&](const TouchedImage& entry) {
                return entry.image == &image;
            })) {
            return Error{std::string(who) + ": image has unsubmitted work in the open recorder"};
        }
    }
    return {};
}

void readback::SubmitAndWait(Backend& backend, Recorder&& recorder) {
    const auto& required = recorder.impl().required_waits;
    std::vector<Wait> waits = required;
    const Stage consumer = recorder.impl().pipeline ? Stage::ComputeShader : Stage::Transfer;
    for (const Wait& wait : required) {
        if (wait.stage != consumer) {
            waits.push_back({wait.value, consumer});
        }
    }
    backend.WaitIdle(backend.Submit(std::move(recorder), waits));
}

Result<void> Backend::PrepareReadback() {
    auto& state = ReadbackState(impl());
    std::lock_guard lock(state.mutex);
    return PrepareKind(*this, state.kinds[0], false);
}

Result<void> Backend::ReadbackToGuest(const Image& image, Rect rect, PicaFormat format, std::span<u8> dest, u32 scale) {
    Image::Impl& input = image.impl();
    if (input.backend.get() != &impl() || input.layers != 1 || !(input.usage & VK_IMAGE_USAGE_SAMPLED_BIT)) {
        return Error{"ReadbackToGuest: image must be sampleable, single-layer and belong to this backend"};
    }
    if (rect.x < 0 || rect.y < 0 || rect.width == 0 || rect.height == 0 ||
        rect.x % kTileSize || rect.y % kTileSize || rect.width % kTileSize || rect.height % kTileSize) {
        return Error{"ReadbackToGuest: expected a nonempty rectangle of aligned 8x8 tiles"};
    }
    if (scale == 0 || static_cast<u64>(rect.x) + rect.width > input.width / scale ||
        static_cast<u64>(rect.y) + rect.height > input.height / scale) {
        return Error{"ReadbackToGuest: scaled rectangle is outside the image"};
    }
    auto output_format = SelectReadbackFormat(format, input.format);
    if (!output_format.ok()) {
        return Error{output_format.error()};
    }
    const u64 pixels = static_cast<u64>(rect.width) * rect.height;
    const u32 pixel_bytes = output_format->bytes;
    if (pixels > dest.size() / pixel_bytes || pixels > Caps().max_storage_buffer_range / pixel_bytes) {
        return Error{"ReadbackToGuest: rectangle exceeds the destination or storage buffer range"};
    }
    const u64 bytes = pixels * pixel_bytes;
    const u32 tiles_x = rect.width / kTileSize;
    const u32 tiles_y = rect.height / kTileSize;
    if (tiles_x > impl().limits.maxComputeWorkGroupCount[0] || tiles_y > impl().limits.maxComputeWorkGroupCount[1]) {
        return Error{"ReadbackToGuest: rectangle exceeds the compute dispatch limits"};
    }
    if (auto submitted = readback::CheckSubmitted(impl(), input, "ReadbackToGuest"); !submitted.ok()) {
        return submitted;
    }

    auto& state = ReadbackState(impl());
    std::lock_guard lock(state.mutex);
    auto& kind = state.kinds[output_format->stencil ? 2 : (output_format->view == ImageView::Depth ? 1 : 0)];
    if (auto result = PrepareKind(*this, kind, output_format->stencil); !result.ok()) {
        return result;
    }
    if (auto result = PrepareBuffers(*this, state, bytes); !result.ok()) {
        return result;
    }

    const VkImageView view = targets::GetView(input, output_format->view);
    const VkImageView stencil = output_format->stencil ? targets::GetView(input, ImageView::Stencil) : VK_NULL_HANDLE;
    if (view == VK_NULL_HANDLE || (output_format->stencil && stencil == VK_NULL_HANDLE)) {
        return Error{"ReadbackToGuest: Vulkan image view unavailable"};
    }
    if (auto result = kind.set->SetStorageBuffer(1, *state.output, 0, bytes); !result.ok()) {
        return result;
    }
    if (auto result = kind.set->SetUniformBuffer(2, *state.params, 0, sizeof(Params)); !result.ok()) {
        return result;
    }
    WriteSampledView(*kind.set, 0, view);
    if (output_format->stencil) {
        WriteSampledView(*kind.set, 3, stencil);
    }
    const Params params{static_cast<u32>(rect.x), static_cast<u32>(rect.y), rect.height, scale,
                        static_cast<u32>(format), pixel_bytes};
    std::memcpy(state.params->Mapped().data(), &params, sizeof(params));
    state.params->Flush(0, sizeof(params));

    Recorder recorder = core::MakeRecorder(impl_, true);
    targets::Acquire(recorder.impl(), input);
    targets::Normalize(recorder.impl(), input);
    recorder.SetPipeline(*kind.pipeline);
    recorder.Bind(*kind.set, 0);
    recorder.Dispatch(tiles_x, tiles_y, 1);
    VkMemoryBarrier host_barrier{};
    host_barrier.sType = VK_STRUCTURE_TYPE_MEMORY_BARRIER;
    host_barrier.srcAccessMask = VK_ACCESS_SHADER_WRITE_BIT;
    host_barrier.dstAccessMask = VK_ACCESS_HOST_READ_BIT;
    vkCmdPipelineBarrier(CommandBuffer(recorder), VK_PIPELINE_STAGE_COMPUTE_SHADER_BIT, VK_PIPELINE_STAGE_HOST_BIT,
                         0, 1, &host_barrier, 0, nullptr, 0, nullptr);
    readback::SubmitAndWait(*this, std::move(recorder));
    if (impl().device_lost.load()) {
        return Error{"ReadbackToGuest: Vulkan device lost"};
    }
    state.output->Invalidate(0, bytes);
    std::memcpy(dest.data(), state.output->Mapped().data(), static_cast<size_t>(bytes));
    return {};
}

