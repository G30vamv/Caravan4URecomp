struct ReadbackFormat {
    u32 bytes;
    ImageView view;
    bool stencil = false;
};

Result<ReadbackFormat> SelectReadbackFormat(PicaFormat guest, Format stored) {
    const bool rgba8 = stored == Format::Rgba8Unorm || stored == Format::Bgra8Unorm;
    const bool depth_stencil = stored == Format::D24S8 || stored == Format::D32S8;
    switch (guest) {
    case PicaFormat::Rgba8:
        if (rgba8) return ReadbackFormat{4, ImageView::Sampled};
        break;
    case PicaFormat::Rgb8:
        if (rgba8) return ReadbackFormat{3, ImageView::Sampled};
        break;
    case PicaFormat::Rgb5A1:
        if (rgba8 || stored == Format::R5G5B5A1 || stored == Format::B5G5R5A1 || stored == Format::A1R5G5B5) {
            return ReadbackFormat{2, ImageView::Sampled};
        }
        break;
    case PicaFormat::Rgb565:
        if (rgba8 || stored == Format::R5G6B5 || stored == Format::B5G6R5) {
            return ReadbackFormat{2, ImageView::Sampled};
        }
        break;
    case PicaFormat::Rgba4:
        if (rgba8 || stored == Format::R4G4B4A4 || stored == Format::B4G4R4A4) {
            return ReadbackFormat{2, ImageView::Sampled};
        }
        break;
    case PicaFormat::D16:
        if (stored == Format::D16Unorm) return ReadbackFormat{2, ImageView::Depth};
        break;
    case PicaFormat::D24:
        if (depth_stencil || stored == Format::D32Float) return ReadbackFormat{3, ImageView::Depth};
        break;
    case PicaFormat::D24S8:
        if (depth_stencil) return ReadbackFormat{4, ImageView::Depth, true};
        break;
    }
    return Error{"ReadbackToGuest: incompatible image and PICA formats"};
}

