// Extract the GLSL below and compile with glslc -fshader-stage=compute --target-env=vulkan1.0 -O.
// Repeat with -DREAD_STENCIL for the second module. The words are the little-endian SPIR-V output.
/* BEGIN GLSL
#version 450
#extension GL_EXT_samplerless_texture_functions : require

layout(local_size_x = 64) in;
layout(set = 0, binding = 0) uniform texture2D source_image;
layout(std430, set = 0, binding = 1) writeonly buffer Output { uint words[]; };
layout(std140, set = 0, binding = 2) uniform Params {
    uvec2 origin;
    uint height;
    uint scale;
    uint format;
    uint pixel_bytes;
};
#ifdef READ_STENCIL
layout(set = 0, binding = 3) uniform utexture2D stencil_image;
#endif

shared uint pixels[64];

// Recover a tile coordinate from the even bits of the Morton index.
uint tile_coordinate(uint index) {
    return (index & 1u) | ((index >> 1u) & 2u) | ((index >> 2u) & 4u);
}

uint encode(ivec2 pos) {
    vec4 sample_value = texelFetch(source_image, pos, 0);
#ifdef READ_STENCIL
    uint depth = uint(sample_value.r * 16777215.0);
    return depth | (texelFetch(stencil_image, pos, 0).r << 24);
#else
    if (format == 5u)
        return uint(roundEven(sample_value.r * 65535.0));
    if (format == 6u)
        return uint(sample_value.r * 16777215.0);

    uvec4 rgba = uvec4(roundEven(sample_value * 255.0));
    switch (format) {
    case 0u: return rgba.a | (rgba.b << 8) | (rgba.g << 16) | (rgba.r << 24);
    case 1u: return rgba.b | (rgba.g << 8) | (rgba.r << 16);
    case 2u: return ((rgba.r >> 3) << 11) | ((rgba.g >> 3) << 6) |
                    ((rgba.b >> 3) << 1) | (rgba.a >> 7);
    case 3u: return ((rgba.r >> 3) << 11) | ((rgba.g >> 2) << 5) | (rgba.b >> 3);
    default: return ((rgba.r >> 4) << 12) | ((rgba.g >> 4) << 8) |
                    ((rgba.b >> 4) << 4) | (rgba.a >> 4);
    }
#endif
}

void main() {
    uint lane = gl_LocalInvocationIndex;
    uvec2 pixel = gl_WorkGroupID.xy * 8u + uvec2(tile_coordinate(lane), tile_coordinate(lane >> 1));
    pixel.y = height - 1u - pixel.y;
    uint value = encode(ivec2((origin + pixel) * scale + scale / 2u));
    uint tile = gl_WorkGroupID.y * gl_NumWorkGroups.x + gl_WorkGroupID.x;
    uint base = tile * 16u * pixel_bytes;
    if (pixel_bytes == 4u) {
        words[base + lane] = value;
        return;
    }
    pixels[lane] = value;
    barrier();
    // Each invocation writing one complete word keeps adjacent pixels from racing on shared bytes.
    if (pixel_bytes == 2u && lane < 32u) {
        words[base + lane] = pixels[lane * 2u] | (pixels[lane * 2u + 1u] << 16);
    } else if (pixel_bytes == 3u && lane < 48u) {
        uint byte_offset = lane * 4u;
        uint first_pixel = byte_offset / 3u;
        uint shift = byte_offset % 3u * 8u;
        words[base + lane] = (pixels[first_pixel] >> shift) | (pixels[first_pixel + 1u] << (24u - shift));
    }
}
END GLSL */

