Result<void> PrepareKind(Backend& backend, ReadbackData::Kind& kind, bool stencil) {
    if (kind.pipeline) {
        return {};
    }

    BindingSetDesc layout{{{0, BindingType::SampledImage}, {1, BindingType::StorageBuffer},
                           {2, BindingType::UniformBuffer}}};
    if (stencil) {
        layout.slots.push_back({3, BindingType::SampledImage});
    }
    ComputePipelineDesc desc;
    desc.shader.spirv = stencil ? std::span<const u32>(kDepthStencilSpirv) : std::span<const u32>(kReadbackSpirv);
    desc.sets.push_back(layout);
    desc.name = "PICA readback";
    auto pipeline = backend.CreateComputePipeline(desc);
    if (!pipeline.ok()) {
        return Error{pipeline.error()};
    }
    auto set = core::MakeBindingSet(backend.impl().shared_from_this(), layout, false);
    if (!set.ok()) {
        return Error{set.error()};
    }
    kind = {std::move(*pipeline), std::move(*set)};
    return {};
}

Result<void> PrepareBuffers(Backend& backend, ReadbackData& state, u64 bytes) {
    if (!state.params) {
        auto params = backend.CreateBuffer({sizeof(Params), Heap::Upload, BufferUsage::Uniform, "Readback parameters"});
        if (!params.ok()) {
            return Error{params.error()};
        }
        state.params = std::move(*params);
    }
    if (!state.output || state.output->Size() < bytes) {
        auto output = backend.CreateBuffer({bytes, Heap::Readback, BufferUsage::Storage, "Readback output"});
        if (!output.ok()) {
            return Error{output.error()};
        }
        state.output = std::move(*output);
    }
    return {};
}

void WriteSampledView(BindingSet& set, u32 binding, VkImageView view) {
    // The public sampled-image setter prepares the thread's open recorder. This dispatch uses an internal recorder.
    const VkDescriptorImageInfo info{VK_NULL_HANDLE, view, VK_IMAGE_LAYOUT_GENERAL};
    auto* descriptors = static_cast<::plume::VulkanDescriptorSet*>(set.impl().set.get());
    descriptors->setDescriptor(binding, nullptr, &info, nullptr, nullptr);
}

